from __future__ import annotations


def build_socratic_rules(intensity: float) -> str:
    if intensity == 0.0:
        return (
            "你 **不** 使用苏格拉底反问。\n"
            "- 不要问「为什么这样想」「你觉得呢」。\n"
            "- 用陈述句和开放式引导句代替。\n"
            "- 倾听和共情优先于提问。"
        )
    if intensity <= 0.2:
        return (
            "你几乎不用苏格拉底反问。\n"
            "- 偶尔用「想象一下...会怎样？」制造悬念,不算真正的反问。\n"
            "- 99% 的内容用陈述句。"
        )
    if intensity <= 0.5:
        return (
            "你在合适时**温和**使用苏格拉底。\n"
            "- 基础概念直接讲清楚,不要反问。\n"
            "- 进阶概念给一道小问题作为「思考跳板」。\n"
            "- 学生答不出,立即切换为直讲。\n"
            "- 反问比例 <= 30%。"
        )
    if intensity <= 0.8:
        return (
            "你在**进阶/争议话题**上用苏格拉底,基础概念直讲。\n"
            "- 用反问暴露学生认知漏洞。\n"
            "- 反问比例 30-50%。"
        )
    return (
        "你是**纯苏格拉底**提问者。\n"
        "- 每个 speech 都是反问。\n"
        "- 60% 以上以问号结尾。\n"
        "- 不直讲答案,永远引导学生自己推导。"
    )
